use crate::db::{Database, TableName};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum TableView {
    #[default]
    Records,
    Columns,
    Indexes,
    ForeignKeys,
    Definition,
}
impl TableView {
    pub const ALL: [Self; 5] = [
        Self::Records,
        Self::Columns,
        Self::Indexes,
        Self::ForeignKeys,
        Self::Definition,
    ];
    pub fn label(self) -> &'static str {
        match self {
            Self::Records => "Records",
            Self::Columns => "Columns",
            Self::Indexes => "Indexes",
            Self::ForeignKeys => "Foreign keys",
            Self::Definition => "DDL",
        }
    }
}
fn literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}
pub fn metadata_sql(db: &Database, table: &TableName, view: TableView) -> String {
    let name = literal(&table.name);
    let schema = literal(&table.schema);
    match (db, view) {
        (_, TableView::Records) => table.preview_sql(matches!(db, Database::Mysql(_))),
        (Database::Sqlite(_), TableView::Columns) => format!(
            "SELECT cid AS position, name, type, [notnull] AS not_null, dflt_value AS default_value, pk AS primary_key, hidden FROM pragma_table_xinfo({name})"
        ),
        (Database::Sqlite(_), TableView::Indexes) => format!(
            "SELECT name, [unique] AS is_unique, origin, partial, (SELECT group_concat(name, ', ') FROM pragma_index_info(i.name)) AS columns FROM pragma_index_list({name}) AS i"
        ),
        (Database::Sqlite(_), TableView::ForeignKeys) => format!(
            "SELECT id, seq, [table] AS referenced_table, [from] AS column_name, [to] AS referenced_column, on_update, on_delete, match FROM pragma_foreign_key_list({name})"
        ),
        (Database::Sqlite(_), TableView::Definition) => format!(
            "SELECT type, name, sql AS definition FROM sqlite_master WHERE (name={name} OR tbl_name={name}) AND sql IS NOT NULL ORDER BY type, name"
        ),
        (Database::Postgres(_) | Database::Mysql(_), TableView::Columns) => format!(
            "SELECT ordinal_position AS position, column_name, data_type, is_nullable, column_default, character_maximum_length FROM information_schema.columns WHERE table_schema={schema} AND table_name={name} ORDER BY ordinal_position"
        ),
        (Database::Postgres(_), TableView::Indexes) => format!(
            "SELECT indexname AS name, indexdef AS definition FROM pg_indexes WHERE schemaname={schema} AND tablename={name} ORDER BY indexname"
        ),
        (Database::Postgres(_), TableView::ForeignKeys) => format!(
            "SELECT c.conname AS name, pg_get_constraintdef(c.oid, true) AS definition FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace WHERE n.nspname={schema} AND t.relname={name} AND c.contype='f' ORDER BY c.conname"
        ),
        (Database::Postgres(_), TableView::Definition) => format!(
            "SELECT 'column' AS kind, a.attname AS name, format_type(a.atttypid,a.atttypmod) || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END || CASE WHEN a.attgenerated<>'' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin,d.adrelid) || ')' || CASE WHEN a.attgenerated='s' THEN ' STORED' ELSE ' VIRTUAL' END ELSE COALESCE(' DEFAULT ' || pg_get_expr(d.adbin,d.adrelid),'') END || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END AS definition FROM pg_attribute a JOIN pg_class t ON t.oid=a.attrelid JOIN pg_namespace n ON n.oid=t.relnamespace LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE n.nspname={schema} AND t.relname={name} AND a.attnum>0 AND NOT a.attisdropped UNION ALL SELECT 'constraint', c.conname, pg_get_constraintdef(c.oid,true) FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace WHERE n.nspname={schema} AND t.relname={name}"
        ),
        (Database::Mysql(_), TableView::Indexes) => format!(
            "SELECT index_name, non_unique, seq_in_index, column_name, collation, index_type FROM information_schema.statistics WHERE table_schema={schema} AND table_name={name} ORDER BY index_name, seq_in_index"
        ),
        (Database::Mysql(_), TableView::ForeignKeys) => format!(
            "SELECT constraint_name, column_name, referenced_table_schema, referenced_table_name, referenced_column_name FROM information_schema.key_column_usage WHERE table_schema={schema} AND table_name={name} AND referenced_table_name IS NOT NULL ORDER BY constraint_name, ordinal_position"
        ),
        (Database::Mysql(_), TableView::Definition) => format!(
            "SHOW CREATE TABLE `{}`.`{}`",
            table.schema.replace('`', "``"),
            table.name.replace('`', "``")
        ),
        (Database::Redis(_), _) => unreachable!("Redis uses typed key inspection"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[tokio::test]
    async fn sqlite_schema_views_include_keys_defaults_and_ddl() {
        let mut db = Database::connect("sqlite::memory:").await.unwrap();
        db.execute("CREATE TABLE parent(id INTEGER PRIMARY KEY); CREATE TABLE \"child's\"(id INTEGER PRIMARY KEY, parent_id INTEGER REFERENCES parent(id), name TEXT NOT NULL DEFAULT 'hello'); CREATE INDEX child_name ON \"child's\"(name);").await.unwrap();
        let table = TableName {
            schema: String::new(),
            name: "child's".into(),
        };
        let columns = db.inspect(&table, TableView::Columns).await.unwrap();
        assert_eq!(columns.rows.len(), 3);
        assert_eq!(columns.rows[2][1], "name");
        assert_eq!(columns.rows[2][3], "1");
        let indexes = db.inspect(&table, TableView::Indexes).await.unwrap();
        assert_eq!(indexes.rows[0][0], "child_name");
        let fks = db.inspect(&table, TableView::ForeignKeys).await.unwrap();
        assert_eq!(fks.rows[0][2], "parent");
        let ddl = db.inspect(&table, TableView::Definition).await.unwrap();
        assert!(ddl.rows.iter().any(|r| r[2].contains("REFERENCES")));
        assert!(
            db.inspect(&table, TableView::Records)
                .await
                .unwrap()
                .rows
                .is_empty()
        );
    }
}
